def subgroups_pm(nu):
    """the subgroups of the units containing -1 and generated with it by at most two elements, largest first."""
    U = CO.units(nu)
    out = set()
    for g1 in U:
        for g2 in U:
            S = {1, nu - 1}
            while True:
                T = S | {(x * g) % nu for x in S for g in (g1, g2)}
                if T == S:
                    break
                S = T
            out.add(frozenset(S))
    return sorted(out, key=lambda S: (-len(S), sorted(S)))


def extends_under(nu, Kp, Lb, phis, S):
    orb = {}
    for u in Kp:
        orb.setdefault(min(min((x * u) % nu, nu - (x * u) % nu) for x in S), []).append(u)
    reps = sorted(orb)
    rows = [[sum(x for u, x in zip(Kp, e) if u in orb[o]) for o in reps] for e in Lb]
    return solve_f2(rows, phis) is not None


def twist_index(nu):
    """least index of a subgroup S (containing -1) such that phi_nu has an S-invariant extension."""
    divisors, Kp, Lb, phis, H, n = obstruction(nu)
    assert divisors == [2]
    U = CO.units(nu)
    if extends_under(nu, Kp, Lb, phis, U):
        return 1
    if any(extends_under(nu, Kp, Lb, phis, [b for b in U if eps[b] == 1]) for eps in quadratic_characters(nu)):
        return 2
    for S in subgroups_pm(nu):
        if extends_under(nu, Kp, Lb, phis, S):
            return len(U) // len(S)


def splitting_rule(nu):
    """True iff some odd prime l | nu has (-1 / l) = (q / l) = 1 for every other prime q | nu."""
    primes = [p for p in range(2, nu + 1) if nu % p == 0 and all(p % r for r in range(2, p))]
    leg = lambda a, l: pow(a % l, (l - 1) // 2, l) == 1
    return any(leg(-1, l) and all(leg(q, l) for q in primes if q != l) for l in primes if l > 2)


