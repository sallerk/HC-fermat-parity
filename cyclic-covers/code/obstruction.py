def residue_functional(m):
    """the obstruction of degree m as a function on residues: phi(alpha) = sum_i cres[alpha_i] mod 2."""
    divisors, Kp, Lb, phis, H, n = obstruction(m)
    assert divisors == [2]
    eps, c = invariant_extension(m, Kp, Lb, phis)
    cres = np.zeros(m, dtype=np.int64)
    for x in range(1, m):
        if 2 * x != m:
            cres[x] = c[min(x, m - x)]
    return cres, eps


def odd_carriers(m, cres, k, limit=3):
    """Hodge tuples of degree m and length 2k with sum cres[x] odd, via half-tuples (an odd tuple splits into an
    odd and an even half; the type vectors of the halves add up to k m (1, ..., 1), compared through a hash)."""
    U = np.array(CO.units(m), dtype=np.int64)
    Q = np.array(list(itertools.combinations_with_replacement(range(1, m), k)), dtype=np.int16)
    par = cres[Q.astype(np.int64)].sum(axis=1) % 2
    w = np.random.default_rng(1).integers(1, 2 ** 20, size=len(U))
    h = np.zeros(len(Q), dtype=np.int64)
    for st in range(0, len(Q), 50000):
        q = Q[st:st + 50000].astype(np.int64)
        h[st:st + 50000] = ((q[:, :, None] * U[None, None, :]) % m).sum(axis=1) @ w
    full = k * m * int(w.sum())
    odd, even = np.nonzero(par == 1)[0], np.nonzero(par == 0)[0]
    order = np.argsort(h[even])
    hs = h[even][order]
    lo = np.searchsorted(hs, full - h[odd], "left")
    hi = np.searchsorted(hs, full - h[odd], "right")
    found = set()
    for i in np.nonzero(hi > lo)[0]:
        for j in even[order[lo[i]:hi[i]]]:
            t = np.concatenate([Q[odd[i]], Q[j]]).astype(np.int64)
            if t.sum() % m == 0 and all(int(((t * u) % m).sum()) == k * m for u in U):
                found.add(tuple(sorted(int(x) for x in t)))
        if len(found) >= limit:
            break
    return sorted(found)


