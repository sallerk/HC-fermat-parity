def law_sample(nu, a):
    Kp, Lb, phis, H, n, eps, c = DATA[nu]
    K, L = CO.det_lattice(nu, a)
    good, outside = True, 0
    for e in L:
        f = dict(zip(K, e))
        pred = sum(Phi(nu, c, f, x) for x in a) % 2
        act = 0 if FT.in_span(H, FT.evec(CO.gamma(nu, a, K, e), nu), n) else 1
        good &= pred == act
        outside |= act
    twist = 1 if eps is None else int(np.prod([eps[x] for x in a]))
    return good, outside, twist


