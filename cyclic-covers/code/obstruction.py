def alpha_p(p):
    d = 3 * p
    S = [x for x in range(1, d) if gcd(x, d) == 1 and x % 3 == 1 and pow(x % p, (p - 1) // 2, p) == 1]
    return tuple(sorted(S + [2 * p]))


