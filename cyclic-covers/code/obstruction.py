def is_composite(n):
    return n > 3 and any(n % p == 0 for p in range(2, int(n ** 0.5) + 1))


def obstruction(nu):
    """(Smith divisors of B_nu / base, Kp, L basis, phi on the basis, base HNF, n)."""
    Kp, Lb = lattice_L(nu)
    H, n = CO.base_span(nu)
    Lv = []
    for e in Lb:
        v = [0] * n
        for u, x in zip(Kp, e):
            v[u - 1] += x
        if nu % 2 == 0 and sum(e) % 2:
            v[-1] += 1
        Lv.append(v)
    Bv = Lv + ([[0] * (n - 1) + [2]] if nu % 2 == 0 else [])
    cols = []
    for j in range(n):
        if flint.fmpq_mat([[v[k] for k in cols + [j]] for v in Bv]).rank() == len(cols) + 1:
            cols.append(j)
        if len(cols) == len(Bv):
            break
    A = flint.fmpq_mat([[v[k] for k in cols] for v in Bv]).transpose()
    coords = []
    for h in H:
        sol = A.solve(flint.fmpq_mat([[h[k]] for k in cols]))
        c = [sol[i, 0] for i in range(len(Bv))]
        assert all(x.q == 1 for x in c)
        assert [sum(int(c[i].p) * Bv[i][k] for i in range(len(Bv))) for k in range(n)] == list(h)
        coords.append([int(x.p) for x in c])
    snf = flint.fmpz_mat(coords).snf()
    divisors = [int(snf[i, i]) for i in range(min(snf.nrows(), snf.ncols())) if snf[i, i] != 1]
    divisors += [0] * (len(Bv) - min(snf.nrows(), snf.ncols()))
    phis = [0 if FT.in_span(H, v, n) else 1 for v in Lv]
    return divisors, Kp, Lb, phis, H, n


def solve_f2(rows, rhs):
    m = len(rows[0])
    A = [[x % 2 for x in r] + [b % 2] for r, b in zip(rows, rhs)]
    piv, r = [], 0
    for c in range(m):
        p = next((i for i in range(r, len(A)) if A[i][c]), None)
        if p is None:
            continue
        A[r], A[p] = A[p], A[r]
        for i in range(len(A)):
            if i != r and A[i][c]:
                A[i] = [x ^ y for x, y in zip(A[i], A[r])]
        piv.append(c)
        r += 1
    if any(not any(row[:-1]) and row[-1] for row in A):
        return None
    sol = [0] * m
    for i, c in enumerate(piv):
        sol[c] = A[i][-1]
    return sol


def count_functionals(nu, Kp, Lb, phis):
    """all c: {g | nu} -> {0, 1} with phi(e) = sum_u c(gcd(u, nu)) e_u mod 2 on L_nu."""
    divs = sorted({gcd(u, nu) for u in Kp})
    return [dict(zip(divs, c)) for c in itertools.product((0, 1), repeat=len(divs))
            if all(sum(c[divs.index(gcd(u, nu))] * x for u, x in zip(Kp, e)) % 2 == ph for e, ph in zip(Lb, phis))]


def quadratic_characters(nu):
    """the quadratic characters eps of (Z/nu)^x with eps(-1) = 1, eps != 1, as dicts on the units."""
    U = CO.units(nu)
    base = []
    for p in range(3, nu + 1, 2):
        if nu % p == 0 and all(p % q for q in range(3, p, 2)):
            base.append(lambda b, p=p: 1 if pow(b, (p - 1) // 2, p) == 1 else -1)
    if nu % 4 == 0:
        base.append(lambda b: 1 if b % 4 == 1 else -1)
    if nu % 8 == 0:
        base.append(lambda b: 1 if b % 8 in (1, 7) else -1)
    out = []
    for r in range(1, len(base) + 1):
        for sub in itertools.combinations(base, r):
            eps = {b: int(np.prod([f(b) for f in sub])) for b in U}
            if eps[nu - 1] == 1 and eps not in out:
                out.append(eps)
    return out


def invariant_extension(nu, Kp, Lb, phis):
    """(eps or None, c on Kp): Phi = sum_u c[u] e_u extends phi and is invariant under ker(eps) (under all units
    if eps is None)."""
    cands = [None] + quadratic_characters(nu)
    for eps in cands:
        S = [b for b in CO.units(nu) if eps is None or eps[b] == 1]
        orb = {}
        for u in Kp:
            orb.setdefault(min(min((s * u) % nu, nu - (s * u) % nu) for s in S), []).append(u)
        reps = sorted(orb)
        rows = [[sum(x for u, x in zip(Kp, e) if u in orb[o]) for o in reps] for e in Lb]
        sol = solve_f2(rows, phis)
        if sol is not None:
            return eps, {u: v for o, v in zip(reps, sol) for u in orb[o]}
    raise AssertionError("no extension")


def Phi(nu, c, f, b):
    """Phi(sigma_b f) for f: Kp -> Z (dict)."""
    s = 0
    for u, x in f.items():
        y = (b * u) % nu
        s += c[min(y, nu - y)] * x
    return s % 2


def random_classes(nu, N, count, rng):
    U = CO.units(nu)
    cl = set()
    for _ in range(100 * count):
        if len(cl) >= count:
            break
        a = [rng.choice(U) for _ in range(N - 1)]
        if (-sum(a)) % nu in U:
            cl.add(min(tuple(sorted((u * x) % nu for x in a + [(-sum(a)) % nu])) for u in U))
    return sorted(cl)


