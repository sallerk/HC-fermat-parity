def decompose_4p(t, p):
    """(A', b, X^-, ok) for a tuple of degree 4p; ok iff the relations of Theorem 12' hold."""
    q = 4 * p
    P, X, Y, Z = {}, {}, {}, {}
    for a in t:
        g = gcd(a, q)
        key, M = {1: ((a % 4, a % p), P), 2: ((a // 2) % p, X), 4: ((a // 4) % p, Y), p: ((a // p) % 4, Z)}.get(
            g, (None, None))
        if M is not None:
            M[key] = M.get(key, 0) + 1
    Po = {(x, y): P.get((x, y), 0) - P.get((4 - x, p - y), 0) for x in (1, 3) for y in range(1, p)}
    A1 = {y: Fraction(Po[(1, y)] + Po[(3, y)], 2) for y in range(1, p)}
    bs = {Fraction(Po[(1, y)] - Po[(3, y)], 2) for y in range(1, p)}
    ok = len(bs) == 1
    b = min(bs)
    Xm = {y: X.get(y, 0) - X.get(p - y, 0) for y in range(1, p)}
    A = {y: A1[y] + Xm[y] for y in range(1, p)}
    ok &= all(Y.get(y, 0) - Y.get(p - y, 0) == A[2 * y % p] - A[y] for y in range(1, p))
    ok &= Z.get(1, 0) - Z.get(3, 0) == ((1 if p % 4 == 1 else -1) - 1) * b
    ok &= all((A1[y] + b).denominator == 1 for y in range(1, p)) and (2 * b).denominator == 1
    return A1, b, Xm, ok


def build_4p(p, A1, b, Xm):
    q = 4 * p
    t = []
    for y in range(1, p):
        for x in (1, 3):
            if (x, y) < (4 - x, p - y):
                v = A1[y] + (b if x == 1 else -b)
                t += [crt(x, 4, y, p) if v > 0 else crt(4 - x, 4, p - y, p)] * abs(int(v))
    for y in range(1, (p + 1) // 2):
        z = y if y % 2 else y + p
        t += [2 * z if Xm[y] > 0 else q - 2 * z] * abs(Xm[y])
    for y in range(1, p):
        v = A1[2 * y % p] + Xm[2 * y % p] - A1[y] - Xm[y]
        if v > 0:
            t += [4 * y % q] * int(v)
    z1 = ((1 if p % 4 == 1 else -1) - 1) * b
    t += [p if z1 > 0 else 3 * p] * abs(int(z1))
    if sum(t) % q:
        t.append(2 * p)
    return tuple(sorted(t))


def snf_job(q):
    import composite as CO
    import obstruction as OB
    CO.base_span = lambda D: FT.span(D, lef=False, cp=False)
    return q, OB.obstruction(q)[0]


def check_P():
    rows, ok = [], True
    for p in (11, 13, 17, 19, 23, 29):
        q = 4 * p
        ts = [t + (2 * p,) if sum(t) % q else t for t in lattice_tuples(q) + list(hodge4(q))]
        good = all(FT.is_hodge(t, q) and decompose_4p(t, p)[3] for t in ts)
        ok &= good
        rows.append({"q": q, "tuples": len(ts), "theorem12p": good})
    rng = random.Random(5)
    built = bad = 0
    for p in (11, 13, 17, 29, 41):
        for _ in range(15):
            half = Fraction(1, 2) if rng.random() < 0.5 else Fraction(0)
            A1, Xm = {}, {}
            for y in range(1, (p + 1) // 2):
                A1[y], Xm[y] = rng.randint(-2, 2) + half, rng.randint(-2, 2)
                A1[p - y], Xm[p - y] = -A1[y], -Xm[y]
            b = rng.randint(-2, 2) + half
            t = build_4p(p, A1, b, Xm)
            built += 1
            dec = decompose_4p(t, p)
            bad += not (FT.is_hodge(t, 4 * p) and dec[3] and dec[1] == b and dec[0] == A1 and dec[2] == Xm)
    ok &= bad == 0
    rows.append({"converse_built": built, "not_hodge_or_wrong": bad})
    nstd = 0
    for p in [r for r in range(3, 60) if isprime(r)]:
        q = 4 * p
        vecs = []
        for Dp in (2 * p, 4 * p):
            for s in standard(Dp):
                t = tuple(sorted((q // Dp) * x % q for x in s))
                A1, b, Xm, dec = decompose_4p(t, p)
                good = FT.is_hodge(t, q) and dec and b.denominator == 1 and all(
                    A1[y].denominator == 1 for y in range(1, p))
                ok &= good
                vecs.append([int(A1[y]) for y in range(1, (p + 1) // 2)] + [int(b)] +
                            [Xm[y] for y in range(1, (p + 1) // 2)])
                nstd += 1
        H = hnf_rows(vecs, p)
        full = len(H) == p and all(H[i][i] == 1 for i in range(p))
        b_ext = decompose_4p(tuple_4p(p)[0], p)[1]
        ok &= full and b_ext.denominator == 2
        rows.append({"q": q, "standard_span_all_integral_triples": full, "b_extremal": str(b_ext)})
    import multiprocessing
    degs = [4 * p for p in range(3, 101) if isprime(p)]
    with multiprocessing.Pool(3) as pool:
        for q, divisors in pool.map(snf_job, degs):
            ok &= divisors == [2]
            rows.append({"q": q, "B_mod_D_plus_S": divisors})
    print("    (P) Theorem 12' on 6 degrees, %d random triples, %d standard tuples; B / (D + S) = Z/2 for %d "
          "degrees 4p: %s" % (built, nstd, len(degs), ok), flush=True)
    return rows, ok


